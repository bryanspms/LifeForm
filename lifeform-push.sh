#!/bin/bash
# Auto-push Unity project to GitHub
# Project: /home/bryan-price/Documents/UnityProjects/LifeForm
# Repo: https://github.com/bryanspms/LifeForm
# Usage: ./lifeform-push.sh ["commit message"]
#        ./lifeform-push.sh  (uses default message with date)

set -e

PROJECT_DIR="/home/bryan-price/Documents/UnityProjects/LifeForm"
REMOTE_URL="https://github.com/bryanspms/LifeForm.git"
BRANCH="main"
COMMIT_MSG="${1:-Auto-update $(date '+%Y-%m-%d %H:%M:%S')}"

if [ ! -d "$PROJECT_DIR" ]; then
  echo "ERROR: Project directory not found: $PROJECT_DIR"
  exit 1
fi

cd "$PROJECT_DIR"

# 1. Init git if needed
if [ ! -d ".git" ]; then
  echo "Initializing git repo..."
  git init -b "$BRANCH"
fi

# 2. Ensure remote 'origin' points to GitHub
if ! git remote get-url origin >/dev/null 2>&1; then
  echo "Adding remote origin -> $REMOTE_URL"
  git remote add origin "$REMOTE_URL"
else
  CURRENT_URL=$(git remote get-url origin)
  if [ "$CURRENT_URL" != "$REMOTE_URL" ]; then
    echo "Updating remote origin from $CURRENT_URL to $REMOTE_URL"
    git remote set-url origin "$REMOTE_URL"
  fi
fi

# 3. Create Unity .gitignore if missing
if [ ! -f ".gitignore" ]; then
  echo "Creating Unity .gitignore..."
  cat > .gitignore << 'EOF'
# Unity generated folders - do NOT commit these
[Ll]ibrary/
[Tt]emp/
[Oo]bj/
[Bb]uild/
[Bb]uilds/
[Ll]ogs/
[Mm]emoryCaptures/
# Asset meta data should be committed, but never the Library

# Autogenerated VS/MonoDevelop/Rider files
*.csproj
*.unityproj
*.sln
*.suo
*.tmp
*.user
*.userprefs
*.pidb
*.booproj
*.svd
*.pdb
*.mdb
*.opendb
*.VC.db

# VS Code
.vscode/
.vs/

# OS generated
.DS_Store
.DS_Store?
._*
.Spotlight-V100
.Trashes
ehthumbs.db
Thumbs.db
*~

# Unity crash reports
sysinfo.txt
crashlytics-build.properties
EOF
fi

# 4. Ensure we are on the correct branch
CURRENT_BRANCH=$(git branch --show-current 2>/dev/null || echo "")
if [ -z "$CURRENT_BRANCH" ]; then
  # No commits yet - will be created on first commit
  git checkout -b "$BRANCH" 2>/dev/null || true
  CURRENT_BRANCH="$BRANCH"
elif [ "$CURRENT_BRANCH" != "$BRANCH" ]; then
  echo "Switching from $CURRENT_BRANCH to $BRANCH..."
  git checkout -B "$BRANCH"
fi

# 5. Stage and commit
git add -A

if git diff --cached --quiet; then
  echo "No changes to commit. Everything is up to date."
else
  echo "Committing: $COMMIT_MSG"
  git commit -m "$COMMIT_MSG"
fi

# 6. Push
echo "Pushing to origin/$BRANCH..."
git push -u origin "$BRANCH"

echo "Done! View at: https://github.com/bryanspms/LifeForm"
