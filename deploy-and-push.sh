#!/bin/bash
# LifeForm Deploy + Push - All-in-one
# 1. Cleans Deployment folder (files only, keeps LifeForm-Linux / LifeForm-Windows)
# 2. 7zips both builds in 20MB chunks
# 3. Deletes old zips in GitHub repo root
# 4. Copies new chunks to GitHub repo root
# 5. Commits + pushes to https://github.com/bryanspms/LifeForm
#
# Usage:
#   ./deploy-and-push.sh ["commit message"]
#   ./deploy-and-push.sh --dry-run ["commit message"]
#   ./deploy-and-push.sh ["commit message"] --dry-run

set -e

PROJECT_DIR="/home/bryan-price/Documents/UnityProjects/LifeForm"
REMOTE_URL="https://github.com/bryanspms/LifeForm.git"
BRANCH="main"

DEPLOY_SRC="/mnt/f9b12936-eaad-4e0c-9526-d7604f290474/UnityProjects/Deployment"
LINUX_FOLDER="LifeForm-Linux"
WINDOWS_FOLDER="LifeForm-Windows"

DRY_RUN=false
COMMIT_MSG=""

for arg in "$@"; do
  if [ "$arg" == "--dry-run" ]; then
    DRY_RUN=true
  elif [ -z "$COMMIT_MSG" ]; then
    COMMIT_MSG="$arg"
  else
    COMMIT_MSG="$COMMIT_MSG $arg"
  fi
done

if [ -z "$COMMIT_MSG" ]; then
  COMMIT_MSG="Deploy builds $(date '+%Y-%m-%d %H:%M:%S')"
fi

run() {
  if [ "$DRY_RUN" = true ]; then
    echo "[DRY-RUN] $*"
  else
    eval "$@"
  fi
}

echo "Commit message: $COMMIT_MSG"
if [ "$DRY_RUN" = true ]; then
  echo "=== DRY RUN MODE - no changes will be made ==="
fi
echo ""

# 0. Verify paths + tools
if [ ! -d "$DEPLOY_SRC" ]; then
  echo "ERROR: Deployment folder not found: $DEPLOY_SRC"
  echo "Check the drive is mounted."
  exit 1
fi
if [ ! -d "$DEPLOY_SRC/$LINUX_FOLDER" ]; then
  echo "ERROR: Missing folder: $DEPLOY_SRC/$LINUX_FOLDER"
  exit 1
fi
if [ ! -d "$DEPLOY_SRC/$WINDOWS_FOLDER" ]; then
  echo "ERROR: Missing folder: $DEPLOY_SRC/$WINDOWS_FOLDER"
  exit 1
fi
if [ ! -d "$PROJECT_DIR" ]; then
  echo "ERROR: Project directory not found: $PROJECT_DIR"
  exit 1
fi
if ! command -v 7z >/dev/null 2>&1; then
  echo "ERROR: 7zip not found. Install with:"
  echo "  sudo apt update && sudo apt install p7zip-full -y"
  exit 1
fi
if ! command -v git >/dev/null 2>&1; then
  echo "ERROR: git not found. Install with: sudo apt install git -y"
  exit 1
fi

echo "=== Step 1: Clean files in Deployment root ==="
ls -la "$DEPLOY_SRC"
echo ""
echo "Root-level files to delete:"
find "$DEPLOY_SRC" -maxdepth 1 -type f -printf "%f (%k KB)\n" || echo "(none)"
echo ""
if [ "$DRY_RUN" = false ]; then
  find "$DEPLOY_SRC" -maxdepth 1 -type f -delete
  rm -f "$DEPLOY_SRC/$LINUX_FOLDER.7z"* "$DEPLOY_SRC/$WINDOWS_FOLDER.7z"*
  echo "Cleaned."
  ls -la "$DEPLOY_SRC"
else
  echo "[DRY-RUN] would delete root-level files + old *.7z chunks"
fi

echo ""
echo "=== Step 2: Compress $LINUX_FOLDER (20MB chunks) ==="
run "cd \"$DEPLOY_SRC\" && 7z a -t7z -mx=7 -v20m \"$LINUX_FOLDER.7z\" \"$LINUX_FOLDER/\""

echo ""
echo "=== Step 3: Compress $WINDOWS_FOLDER (20MB chunks) ==="
run "cd \"$DEPLOY_SRC\" && 7z a -t7z -mx=7 -v20m \"$WINDOWS_FOLDER.7z\" \"$WINDOWS_FOLDER/\""

if [ "$DRY_RUN" = false ]; then
  echo ""
  echo "New archives:"
  ls -lh "$DEPLOY_SRC"/*.7z.* || (echo "ERROR: No chunks created!" && exit 1)
fi

echo ""
echo "=== Step 4: Git setup for $PROJECT_DIR ==="
cd "$PROJECT_DIR"

if [ ! -d ".git" ]; then
  echo "Initializing git repo..."
  if [ "$DRY_RUN" = false ]; then
    git init -b "$BRANCH"
  else
    echo "[DRY-RUN] git init -b $BRANCH"
  fi
fi

if ! git remote get-url origin >/dev/null 2>&1; then
  echo "Adding remote origin -> $REMOTE_URL"
  run "git remote add origin \"$REMOTE_URL\""
else
  CURRENT_URL=$(git remote get-url origin)
  if [ "$CURRENT_URL" != "$REMOTE_URL" ]; then
    echo "Updating remote origin from $CURRENT_URL to $REMOTE_URL"
    run "git remote set-url origin \"$REMOTE_URL\""
  else
    echo "Remote origin OK: $CURRENT_URL"
  fi
fi

if [ ! -f ".gitignore" ]; then
  echo "Creating Unity .gitignore..."
  if [ "$DRY_RUN" = false ]; then
    cat > .gitignore << 'EOF'
# Unity generated folders - do NOT commit these
[Ll]ibrary/
[Tt]emp/
[Oo]bj/
[Bb]uild/
[Bb]uilds/
[Ll]ogs/
[Mm]emoryCaptures/
# Autogenerated VS/MonoDevelop/Rider files
*.csproj
*.unityproj
*.sln
*.suo
*.tmp
*.user
*.userprefs
*.pidb
*.booproj
*.svd
*.pdb
*.mdb
*.opendb
*.VC.db
# VS Code
.vscode/
.vs/
# OS generated
.DS_Store
.DS_Store?
._*
.Spotlight-V100
.Trashes
ehthumbs.db
Thumbs.db
*~
# Unity crash reports
sysinfo.txt
crashlytics-build.properties
EOF
  else
    echo "[DRY-RUN] would create .gitignore"
  fi
fi

CURRENT_BRANCH=$(git branch --show-current 2>/dev/null || echo "")
if [ -z "$CURRENT_BRANCH" ]; then
  echo "No commits yet, creating branch $BRANCH"
  run "git checkout -b \"$BRANCH\" 2>/dev/null || true"
elif [ "$CURRENT_BRANCH" != "$BRANCH" ]; then
  echo "Switching from $CURRENT_BRANCH to $BRANCH..."
  run "git checkout -B \"$BRANCH\""
fi

echo ""
echo "=== Step 5: Delete old zips in GitHub root, copy new chunks ==="
echo "Old archives in $PROJECT_DIR:"
find "$PROJECT_DIR" -maxdepth 1 -type f \( -iname "*.zip*" -o -iname "*.7z*" \) -printf "%f (%k KB)\n" || echo "(none)"
if [ "$DRY_RUN" = false ]; then
  find "$PROJECT_DIR" -maxdepth 1 -type f \( -iname "*.zip*" -o -iname "*.7z*" \) -delete || true
  echo "Deleted old archives."
  cp -v "$DEPLOY_SRC/$LINUX_FOLDER.7z"* "$PROJECT_DIR/"
  cp -v "$DEPLOY_SRC/$WINDOWS_FOLDER.7z"* "$PROJECT_DIR/"
  echo ""
  echo "New archives in GitHub root:"
  ls -lh "$PROJECT_DIR"/*.7z.* || (echo "ERROR: Copy failed!" && exit 1)
else
  echo "[DRY-RUN] would delete old *.zip/*.7z in root and copy new chunks"
fi

echo ""
echo "=== Step 6: Commit + Push to GitHub ==="
if [ "$DRY_RUN" = false ]; then
  git add -A
  if git diff --cached --quiet; then
    echo "No changes to commit. Everything is up to date."
  else
    echo "Committing: $COMMIT_MSG"
    git commit -m "$COMMIT_MSG"
  fi
  echo "Pushing to origin/$BRANCH..."
  git push -u origin "$BRANCH"
  echo ""
  echo "Done! View at: https://github.com/bryanspms/LifeForm"
else
  echo "[DRY-RUN] would run: git add -A, git commit, git push -u origin $BRANCH"
  echo ""
  echo "Dry run complete. Re-run without --dry-run to execute."
fi
